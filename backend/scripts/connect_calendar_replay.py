"""Replay for freeze exception 3 (P2-D28, P2 spec §4.11): the roadmap time estimate with
CONNECT_CALENDAR_FROM_KNOWLEDGE off and on.

Every study field x four fictional students x three days is estimated three times:
  off       - the flag off (today's product);
  on        - the flag and the `counsellor` module on, with the shipped links (policy_links.yaml);
  on+fact   - as `on`, plus one fictional link and confirmed fact (the Part-2 result in August).
The report lists every estimate that differs from `off`. No model call, no network, no database: the Knowledge read
is stubbed with the fictional fact.

CLI (from backend/): python -m scripts.connect_calendar_replay --out ../docs/connect/replays/p2/calendar-from-knowledge.md
"""

import argparse
import sys
from datetime import date
from pathlib import Path
from unittest.mock import patch

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from app import pai_os_bridge  # noqa: E402
from app.config import config  # noqa: E402
from app.pai_c.connect import policy_knowledge as pk  # noqa: E402
from app.pai_c.paths.fields import study_fields  # noqa: E402
from app.pai_c.roadmap.timeline import estimate  # noqa: E402
from tests.test_roadmap_steps import fsc, route  # noqa: E402

DAYS = (date(2026, 10, 29), date(2027, 3, 1), date(2027, 7, 15))
STUDENTS = {
    "fsc_pre_engineering_current": fsc("pre_engineering", status="current"),
    "fsc_pre_medical_70": fsc("pre_medical", 70),
    "fsc_pre_engineering_50": fsc("pre_engineering", 50),
    "matric_current": {"qualification_name": "matric", "academic_status": "current"},
}
LINK = {"target": "event", "key": "hssc_part2_result", "attr": "months",
        "fact": {"scope": "registry", "ref": "cal:alpha-result", "field": "result_date"}}
FACT = {"value": {"date": "2027-08-14", "tz": "UTC"}, "url": "https://alpha.example/notice", "status": "confirmed",
        "intake_year": 2027}


def grid() -> dict:
    out = {}
    for day in DAYS:
        for field in sorted(study_fields()):
            for name, record in STUDENTS.items():
                out[(day.isoformat(), field, name)] = estimate(route(field, record), field, day)
    return out


def run(mode: str) -> dict:
    pk.clear()
    with patch.object(config, pk.PART, mode != "off"), \
            patch.object(pai_os_bridge, "counsellor_module_on", lambda: True):
        if mode != "on+fact":
            return grid()
        shipped = pk.links()
        with patch.object(pk, "links", lambda: {**shipped, "calendar": [*shipped["calendar"], LINK]}), \
                patch.object(pai_os_bridge, "confirmed_knowledge",
                             lambda keys, year: {tuple(k): FACT for k in keys if tuple(k) == pk._key(LINK)}):
            return grid()


def report() -> tuple[str, bool]:
    off, on, fact = run("off"), run("on"), run("on+fact")
    pk.clear()
    changed_on = [k for k in off if on[k] != off[k]]
    changed_fact = [k for k in off if fact[k] != off[k]]
    uses = {k for k in off if any(b["event_key"] == LINK["key"] for b in off[k]["basis"])}
    only_intended = set(changed_fact) <= uses and all(
        [b for b in fact[k]["basis"] if b["event_key"] == LINK["key"]][0]["month"] == 8 for k in changed_fact)
    ok = not changed_on and only_intended
    lines = [
        "# Replay: CONNECT_CALENDAR_FROM_KNOWLEDGE (freeze exception 3)",
        "",
        "Generated by `python -m scripts.connect_calendar_replay`. Offline: no model call, no network, no database.",
        "",
        f"- Estimates per run: {len(off)} ({len(study_fields())} study fields x {len(STUDENTS)} students x "
        f"{len(DAYS)} days).",
        f"- `on` (shipped links) vs `off`: **{len(changed_on)} differ**.",
        f"- `on+fact` (one fictional confirmed Part-2 result date, August) vs `off`: **{len(changed_fact)} differ**; "
        f"{len(uses)} estimates use that event; every difference is in one of them, with the event in month 8: "
        f"**{'yes' if only_intended else 'NO'}**.",
        "",
        f"Result: **{'only the intended values changed' if ok else 'UNEXPECTED DIFFERENCES'}**.",
        "",
        "## Differences in `on+fact` (first 20)",
        "",
        "| day | field | student | Part-2 result month (off -> on) | to entry (off -> on) | confidence (off -> on) |",
        "|---|---|---|---|---|---|",
    ]
    for k in sorted(changed_fact)[:20]:
        months = [next(b["month"] for b in run_[k]["basis"] if b["event_key"] == LINK["key"]) for run_ in (off, fact)]
        lines.append(f"| {k[0]} | {k[1]} | {k[2]} | {months[0]} -> {months[1]} | {off[k]['to_entry_months']} -> {fact[k]['to_entry_months']} | "
                     f"{off[k]['confidence']} -> {fact[k]['confidence']} |")
    return "\n".join(lines) + "\n", ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    text, ok = report()
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
    print(text)
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
